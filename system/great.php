<?php

// =========================================================
// MYJAT — GREAT PAGE ENTRY
// Uses the same VIP renderer as all other pages
// =========================================================

require_once __DIR__ . '/../vip/bootstrap.php';


// =========================================================
// GET SLUG
// =========================================================

$slug = $_GET['slug'] ?? '';


// =========================================================
// FIND GREAT FUNCTION
// =========================================================

$function = 'myjat_' . $slug . '_home';


// =========================================================
// 404
// =========================================================

if (
    !$slug
    ||
    !function_exists($function)
) {

    http_response_code(404);

    exit(
        'Great page not found.'
    );
}


// =========================================================
// DATABASE
// =========================================================

$pdo = $GLOBALS['pdo'] ?? null;


// =========================================================
// GENERATE CONTENT
// =========================================================

$content =
    myjat_vip_render_function(
        $function,
        $pdo
    );


// =========================================================
// SAME GLOBAL RENDERER
// =========================================================

myjat_vip_render_page(
    $content
);